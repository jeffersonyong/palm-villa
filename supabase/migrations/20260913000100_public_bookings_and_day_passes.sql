-- 8. The read model carries what the public flow writes.
--
-- Appended, because `create or replace view` allows a new column only at the
-- end (the lesson paid_cents and deposit_waiver_reason already recorded).
--
-- booking_summary gains the guest's email, the pass date and the headcount.
-- The pass date is what makes prd.md §6.1's promise legible on a screen: the
-- bookings register has been drawing an em dash in its Dates cell for every
-- day pass, correctly, because there was no date to draw. Now there is.
--
-- payment_summary gains the pass date for the same reason — the verification
-- queue's Arriving column reads occupancy, and a day pass has none.
-- ═══════════════════════════════════════════════════════════════════════════

create or replace view booking_summary
with (security_invoker = true)
as
select
  b.id,
  b.property_id,
  b.reference,
  b.status,
  b.stream,
  g.name as guest_name,
  g.phone as guest_phone,
  b.chargeable_guests,
  b.exempt_guests,
  b.total_cents,
  b.security_deposit_cents,
  b.hold_expires_at,
  b.created_at,
  b.updated_at,
  b.no_vehicle,
  o.unit_id,
  u.ref as unit_ref,
  ut.slug as unit_type_slug,
  o.start_date as check_in,
  o.end_date as check_out,
  coalesce(l.lines, '[]'::jsonb) as lines,
  coalesce(v.vehicles, '[]'::jsonb) as vehicles,
  b.discount_kind,
  b.discount_value,
  b.discount_reason,
  coalesce(pay.paid_cents, 0)::integer as paid_cents,
  b.deposit_waiver_reason,
  g.email as guest_email,
  dp.pass_date,
  dp.headcount as pass_headcount,
  b.access_token
from booking b
join guest g on g.id = b.guest_id
left join occupancy o on o.booking_id = b.id
left join unit u on u.id = o.unit_id
left join unit_type ut on ut.id = u.unit_type_id
left join day_pass dp on dp.booking_id = b.id
left join lateral (
  select jsonb_agg(
    jsonb_build_object(
      'type', bl.line_type,
      'description', bl.description,
      'quantity', bl.quantity,
      'unitPrice', bl.unit_price_cents,
      'amount', bl.amount_cents
    )
    order by bl.sort_order
  ) as lines
  from booking_line bl
  where bl.booking_id = b.id
) l on true
left join lateral (
  select jsonb_agg(bv.registration order by bv.sort_order) as vehicles
  from booking_vehicle bv
  where bv.booking_id = b.id
) v on true
left join lateral (
  select sum(p.amount_cents) as paid_cents
  from payment p
  where p.booking_id = b.id and p.status = 'verified'
) pay on true;

create or replace view payment_summary
with (security_invoker = true)
as
select
  p.id,
  p.property_id,
  p.booking_id,
  p.method,
  p.status,
  p.expected_amount_cents,
  p.amount_cents,
  p.observed_reference,
  p.observed_sender,
  p.observed_on,
  p.match_kind,
  p.amount_override_reason,
  p.match_reason,
  p.collected_by,
  p.collected_at,
  p.verified_by,
  p.verified_at,
  p.created_by,
  p.created_at,
  p.slip_document_id,
  b.reference as booking_reference,
  b.status as booking_status,
  (b.total_cents - coalesce(other.paid_cents, 0))::integer as due_amount_cents,
  b.updated_at as booking_updated_at,
  g.name as guest_name,
  g.phone as guest_phone,
  o.start_date as check_in,
  u.ref as unit_ref,
  b.stream as booking_stream,
  dp.pass_date
from payment p
join booking b on b.id = p.booking_id
join guest g on g.id = b.guest_id
left join occupancy o on o.booking_id = b.id
left join unit u on u.id = o.unit_id
left join day_pass dp on dp.booking_id = b.id
left join lateral (
  select sum(other_payment.amount_cents) as paid_cents
  from payment other_payment
  where other_payment.booking_id = b.id
    and other_payment.status = 'verified'
    and other_payment.id <> p.id
) other on true;

